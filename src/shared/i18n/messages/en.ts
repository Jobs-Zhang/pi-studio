/**
 * Every literal key defined by the English source catalog. Catalogs are typed
 * against this, so a missing or renamed key is a compile error before the
 * plural-base keys of `PiStudioMessageKey` widen what callers may ask for.
 */
export type PiStudioCatalogKey = keyof typeof en;

/**
 * Every message key a caller may pass to `t`: the catalog keys, plus the plural
 * bases of keys such as `session.messages_one` / `session.messages_other`.
 * Callers pass the base key with a numeric `count`, and the translator selects
 * the CLDR category with `Intl.PluralRules`.
 */
export type PiStudioMessageKey = PiStudioCatalogKey | PluralMessageBase<PiStudioCatalogKey>;

type PluralCategory = "zero" | "one" | "two" | "few" | "many" | "other";

type PluralMessageBase<Key extends string> = Key extends `${infer Base}_${PluralCategory}` ? Base : never;
